// 题型范围：地级行政区 / 直辖市市辖区 / 两者混合
export const SCOPE_DIVISION = 'division'
export const SCOPE_DISTRICT = 'district'
export const SCOPE_ALL = 'all'

function flatten(sources, scope) {
  const units = []
  for (const p of sources) {
    for (const name of p.divisions) {
      units.push({ name, province: p.name, scope })
    }
  }
  return units
}

