/** 地级行政区的四种类别，用于生成难度更接近的干扰项。 */
export function divisionKind(name) {
  if (name.endsWith('自治州')) return '自治州'
  if (name.endsWith('地区')) return '地区'
  if (name.endsWith('盟')) return '盟'
  if (name.endsWith('区')) return '市辖区'
  return '地级市'
}

